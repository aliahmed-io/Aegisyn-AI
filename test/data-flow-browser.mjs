import { chromium } from 'playwright';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1327,height:863}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 console.log('Loading dataset page');
 await page.goto('http://localhost:3001/datasets');
 await page.getByLabel('Upload flow CSV').setInputFiles({name:'verification.csv',mimeType:'text/csv',buffer:Buffer.from((await readFile('data/unsw_nb15_sample.csv','utf8')).split(/\r?\n/).slice(0,13).join('\n'))});
 await page.getByRole('button',{name:'Analyze dataset',exact:true}).click();
 console.log('Analysis started');
 await page.getByRole('status').filter({hasText:'Analysis completed'}).waitFor({timeout:30000});
 console.log('Analysis completed');
 await page.getByRole('link',{name:'View dashboard'}).click();
 await page.waitForFunction(()=>document.querySelector('.metric-card strong')?.textContent==='12');
 assert.equal(await page.getByText('Local workspace',{exact:true}).count(),0);
 assert.equal(await page.getByText('No account required',{exact:true}).count(),0);
 assert.equal(await page.locator('img[alt="Aegisyn logo"]:visible').count(),1);
 assert.ok(await page.locator('link[rel="icon"]').first().getAttribute('href'));
 console.log('Logo and dashboard verified');
 await page.reload();await page.waitForFunction(()=>document.querySelector('.metric-card strong')?.textContent==='12');
 await page.screenshot({path:'reports/real-data-verification.png'});
 console.log('Persistence verified');
 await page.getByRole('link',{name:'Reports',exact:true}).click();
 const download=page.waitForEvent('download');
 await page.getByRole('link',{name:'Download predictions CSV'}).click();
 const file=await download;console.log('Export downloaded');assert.ok(file.suggestedFilename().endsWith('.csv'));
 const stream=await file.createReadStream();let csv='';for await(const chunk of stream)csv+=chunk;
 assert.equal(csv.trim().split('\n').length,13);
 assert.ok(csv.includes('malicious_probability'));
 console.log('CSV verified');
 await page.getByRole('link',{name:'Settings',exact:true}).click();
 await page.getByLabel('Animate scan').setChecked(false);
 await page.getByLabel('Projection').selectOption('tactical');
 await page.getByRole('button',{name:'Save preferences'}).click();
 await page.getByRole('link',{name:'Threat Sonar',exact:true}).click();
 await page.getByRole('button',{name:'Tactical'}).waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://localhost:3001/datasets');
 assert.equal(await page.locator('main:visible').evaluate(e=>e.scrollWidth<=e.clientWidth),true);
 assert.equal(await page.getByRole('link',{name:'Overview',exact:true}).isVisible(),true);
 await page.screenshot({path:'reports/datasets-mobile.png'});
 await page.route('**/api/**',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Analysis service unavailable. Start the backend and try again.'})}));
 await page.goto('http://localhost:3001/overview');
 await page.getByRole('alert').waitFor();
 assert.equal(await page.locator('.metric-card strong').first().textContent(),'0');
 assert.deepEqual(errors,[]);
 console.log('PASS: actual HTTP upload, model inference, persisted dashboard, CSV export, logo/icon, saved preferences, mobile layout, honest offline state; no browser errors.');
} finally {await browser.close();}
